#!/usr/bin/env bash
# 步骤 1：进 BROM 模式并读取分区表（只读，不改任何东西）
# 用法：bash ~/TB310FU-启天K9/1-检测设备.sh
set -uo pipefail
HERE="$(cd "$(dirname "$0")/.." && pwd)"
cd "$HERE/mtkclient"

cat <<'TIP'
────────────────────────────────────────────────────────
 现在按顺序做：
   1. 平板【完全关机】（长按电源键，确认黑屏）
   2. 按住【音量 −】不放（不行就换【音量 +】，或两个一起按）
   3. 把 USB 线插到这台电脑（主板后置口，别用扩展坞）
   4. 等下面刷出日志后，再松开音量键
────────────────────────────────────────────────────────
TIP
read -r -p "按回车开始（此时平板应已关机、线未插）..." _

"$HERE/venv/bin/python" mtk.py printgpt
RC=$?
echo
if [ $RC -eq 0 ]; then
  echo "✔ 成功读到分区表，说明 BROM 已打通（MT6768/6769 支持）。"
  echo "  下一步：bash ~/TB310FU-启天K9/2-备份分区.sh"
else
  echo "✘ 没读到。常见原因："
  echo "  · 没进 BROM：换【音量 -】再试；或先按住音量+再插线"
  echo "  · 平板其实在充电/已开机：彻底关机后 10 秒再试"
  echo "  · 驱动权限：确认跑过 0-环境准备.sh，并重插 USB"
  echo "  · 换一个 USB 口（直连主板，别用扩展坞）"
fi
